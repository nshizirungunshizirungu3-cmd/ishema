            'DB_HOST' => getenv('DB_HOST') ?: 'localhost',
            'DB_PORT' => getenv('DB_PORT') ?: '3306',
            'DB_NAME' => getenv('DB_NAME') ?: 'ishema_system',
            'DB_USER' => getenv('DB_USER') ?: 'root',
            'DB_PASS' => getenv('DB_PASS') ?: '',
        ];

        try {
            $pdo = testDb($cfg);
        } catch (Throwable $ex) {
            $errors[] = 'Database connection failed: ' . $ex->getMessage();
        }

        if (!$errors) {
            try {
                $pdo->exec('CREATE DATABASE IF NOT EXISTS `' . $cfg['DB_NAME'] . '` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci');
                $pdo->exec('USE `' . $cfg['DB_NAME'] . '`');
                $n = importSql($pdo, DATABASE_PATH . 'schema.sql');
                $success[] = "Database schema imported ($n statements).";
            } catch (Throwable $ex) {
                $errors[] = 'Schema import failed: ' . $ex->getMessage();
            }
        }

        // create super admin
        if (!$errors) {
            try {
                $name = (string)(getenv('SUPER_ADMIN_NAME') ?: 'Super Administrator');
                $email = mb_strtolower(trim((string)(getenv('SUPER_ADMIN_EMAIL') ?: 'admin@ishema.com')));
                $password = (string)(getenv('SUPER_ADMIN_PASSWORD') ?: '');
                if (strlen($password) < 8) { throw new RuntimeException('Super admin password too short.'); }

                $existing = $pdo->query('SELECT id FROM users WHERE email = ' . $pdo->quote($email) . ' AND deleted_at IS NULL')->fetch();
                if ($existing) {
                    $success[] = 'Super admin already exists (' . $email . ').';
                } else {
                    $stmt = $pdo->prepare('INSERT INTO users (name, email, phone, password, role, language, is_active, email_verified_at) VALUES (?, ?, NULL, ?, "SUPER_ADMIN", "en", 1, NOW())');
                    $stmt->execute([$name, $email, password_hash($password, PASSWORD_DEFAULT)]);
                    $success[] = 'Super administrator created: ' . $email;
                }
            } catch (Throwable $ex) {
                $errors[] = 'Super admin creation failed: ' . $ex->getMessage();
            }
        }

        // seed default packages
        if (!$errors) {
            try {
                $count = (int)$pdo->query('SELECT COUNT(*) c FROM packages')->fetch()['c'];
                if ($count === 0) {
                    $packages = [
                        ['Starter', 'starter', 29.00, 290.00, 5, 0, 10, 50, 1, '["restaurant"]', '["menu_management","orders","basic_reports"]', 'email', 1, 0],
                        ['Professional', 'professional', 79.00, 790.00, 20, 20, 50, 300, 2, '["restaurant","hotel"]', '["menu_management","orders","hotel_management","advanced_reports","staff_management"]', 'priority', 1, 0],
                        ['Enterprise', 'enterprise', 199.00, 1990.00, 100, 200, 200, 2000, 10, '["restaurant","hotel"]', '["all_modules","api_access","priority_support","multi_branch"]', 'dedicated', 1, 0],
                    ];
                    $stmt = $pdo->prepare('INSERT INTO packages (name, slug, price_monthly, price_yearly, max_employees, max_rooms, max_tables, max_products, max_branches, modules, features, support_level, has_reports, is_default, status, sort_order) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, 1, ?, "active", ?)');
                    foreach ($packages as $i => $p) {
                        $stmt->execute([$p[0], $p[1], $p[2], $p[3], $p[4], $p[5], $p[6], $p[7], $p[8], $p[9], $p[10], $p[11], $i === 0 ? 1 : 0, $i * 10]);
                    }
                    $success[] = 'Default packages seeded (Starter, Professional, Enterprise).';
                }
            } catch (Throwable $ex) {
                $errors[] = 'Package seeding failed: ' . $ex->getMessage();
            }
        }

        // optional demo data
        if (!$errors && isset($_POST['seed_demo'])) {
            require DATABASE_PATH . 'seeds/DatabaseSeeder.php';
            try {
                \App\Seeds\DatabaseSeeder::run($pdo);
                $success[] = 'Demo data seeded.';
            } catch (Throwable $ex) {
                $errors[] = 'Demo seeding failed: ' . $ex->getMessage();
            }
        }

        if (!$errors) {
            file_put_contents($lockFile, date('c') . PHP_EOL);
            $installed = true;
        }
    }
}

