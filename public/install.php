// ---------------------------------------------------------------------------
// Helpers
// ---------------------------------------------------------------------------
function e(?string $v): string
{
    return htmlspecialchars((string)$v, ENT_QUOTES, 'UTF-8');
}

function writeEnv(array $data): void
{
    global $envFile;
    $lines = ["# ISHEMA - Hotel & Restaurant Management System", "# Generated by install.php", ''];
    foreach ($data as $k => $v) {
        $lines[] = $k . '=' . $v;
    }
    file_put_contents($envFile, implode(PHP_EOL, $lines) . PHP_EOL);
}

/** Load .env values into the process environment (same logic as public/index.php). */
function loadEnv(string $path): void
{
    foreach (file($path, FILE_IGNORE_NEW_LINES | FILE_SKIP_EMPTY_LINES) as $line) {
        if (str_starts_with(trim($line), '#')) { continue; }
        if (str_contains($line, '=')) {
            [$k, $v] = explode('=', $line, 2);
            $k = trim($k);
            $v = trim($v);
            if (($v[0] ?? '') === '"' && substr($v, -1) === '"') { $v = substr($v, 1, -1); }
            if (!isset($_ENV[$k]) && !isset($_SERVER[$k])) {
                putenv("$k=$v");
                $_ENV[$k] = $v;
                $_SERVER[$k] = $v;
            }
        }
    }
}

function testDb(array $cfg): PDO
{
    $dsn = "mysql:host={$cfg['DB_HOST']};port={$cfg['DB_PORT']};charset=utf8mb4";
    return new PDO($dsn, $cfg['DB_USER'], $cfg['DB_PASS'], [
        PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION,
        PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC,
    ]);
}

/** Import a .sql file, statement by statement (no stored procedures in schema). */
function importSql(PDO $pdo, string $file): int
{
    $sql = file_get_contents($file);
    if ($sql === false) { throw new RuntimeException("Cannot read $file"); }
    $sql = preg_replace('/--[^\n]*/', '', $sql);
    $sql = preg_replace('/\/\*.*?\*\//s', '', $sql);
    $statements = array_filter(array_map('trim', explode(';', $sql)), fn($s) => $s !== '');
    $count = 0;
    foreach ($statements as $stmt) {
        $pdo->exec($stmt);
        $count++;
    }
    return $count;
}

